package com.splitapp.user

import org.junit.jupiter.api.Test
import org.junit.jupiter.api.assertThrows
import org.springframework.beans.factory.annotation.Autowired
import org.springframework.boot.data.jpa.test.autoconfigure.DataJpaTest
import org.springframework.boot.jdbc.test.autoconfigure.AutoConfigureTestDatabase
import org.springframework.dao.DataIntegrityViolationException
import org.springframework.test.context.ActiveProfiles
import kotlin.test.assertEquals
import kotlin.test.assertFalse
import kotlin.test.assertNotNull
import kotlin.test.assertNull
import kotlin.test.assertTrue

// @DataJpaTest starts only the database part of the app (entities, repositories, Flyway).
// Every test runs inside a transaction that is rolled back at the end,
// so the splitapp_test database is empty again for the next test.
@DataJpaTest
// By default @DataJpaTest wants an in-memory database; NONE = "use the real PostgreSQL from the config".
@AutoConfigureTestDatabase(replace = AutoConfigureTestDatabase.Replace.NONE)
@ActiveProfiles("test")
class UserRepositoryTest(@Autowired private val userRepository: UserRepository) {

    @Test
    fun `save gives the user an id generated by the database`() {
        val user = User(name = "Ceyda", email = "ceyda@example.com", passwordHash = "hash")
        assertNull(user.id)

        val saved = userRepository.save(user)

        assertNotNull(saved.id)
    }

    @Test
    fun `findByEmail returns the saved user`() {
        userRepository.save(User(name = "Ceyda", email = "ceyda@example.com", passwordHash = "hash"))

        val found = userRepository.findByEmail("ceyda@example.com")

        assertNotNull(found)
        assertEquals("Ceyda", found.name)
        assertEquals("hash", found.passwordHash)
    }

    @Test
    fun `findByEmail returns null when no user has that email`() {
        assertNull(userRepository.findByEmail("nobody@example.com"))
    }

    @Test
    fun `existsByEmail tells whether the email is taken`() {
        userRepository.save(User(name = "Ceyda", email = "ceyda@example.com", passwordHash = "hash"))

        assertTrue(userRepository.existsByEmail("ceyda@example.com"))
        assertFalse(userRepository.existsByEmail("other@example.com"))
    }

    @Test
    fun `database rejects two users with the same email`() {
        userRepository.saveAndFlush(User(name = "Ceyda", email = "ceyda@example.com", passwordHash = "hash"))

        // The UNIQUE constraint on users.email (from V1__create_users.sql) protects us
        // even if our code forgets to check first.
        assertThrows<DataIntegrityViolationException> {
            userRepository.saveAndFlush(User(name = "Copy", email = "ceyda@example.com", passwordHash = "hash"))
        }
    }
}
